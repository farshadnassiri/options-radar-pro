// ۲۱۹. پوستهٔ برنامه — از شیشه به کاغذ
//
// ═══ چرا نامش عوض شد ═══
//
// این دسته برای پوستهٔ **شیشه‌ای** نوشته شد. صاحب پروژه بعداً گفت:
// «ui سایت رو تغییر بده … المانهای جدید و مینیمال.» پس شیشه رفت و
// سطحِ مات آمد. ادعاهای این دسته اما بیشترشان ربطی به شیشه نداشتند —
// سه اشکالِ واقعی را قفل می‌کردند که هر پوسته‌ای می‌تواند دوباره
// بسازدشان. آن‌ها ماندند؛ فقط ادعایی که مخصوصِ شیشه بود جایش را به
// ادعای مینیمال داد.
//
// ═══ چرا این دسته هست ═══
//
// بازطراحی ظاهر یک تغییر «بی‌خطر» به نظر می‌رسد و نیست. سه اشکالِ واقعی
// در همین بازطراحی رخ داد که هیچ‌کدام از خواندنِ کد پیدا نشدند — هر سه
// را اجرای واقعی در مرورگر و **سنجشِ عددیِ کنتراست** پیدا کرد:
//
//   ۱. زمینه به `html` منتقل شد تا لکه‌های نور دیده شوند. ولی `--ground`
//      پوستهٔ تیره روی `body[data-theme="board"]` تعریف شده، پس `html`
//      هرگز آن را نمی‌بیند و زمینه در پوستهٔ تیره **روشن** ماند. عنوانِ
//      سفیدِ صفحه روی آن به نسبت کنتراست ۱٫۱۸ رسید — عملاً نامرئی.
//   ۲. نوارِ نورِ کارت با درصد تمام می‌شد، پس در کارتِ بلند روی متن
//      می‌افتاد و در پوستهٔ تیره کلِ ردیفِ برچسب‌ها را خاکستری‌روی‌خاکستری
//      کرد.
//   ۳. `.subtabs` مقدار `display` می‌گذارد و صفتِ `hidden` را می‌شکند؛
//      یک جعبهٔ خالیِ شیشه‌ای وسط صفحه می‌ماند.
//
// این دسته هر سه را قفل می‌کند. سنجشِ کنتراست خودش اینجا اجرا نمی‌شود —
// مرورگر لازم دارد — ولی **شرطِ ساختاری‌ای** که آن سه اشکال را ممکن کرد
// اینجا قفل است.

import { check, group, readSrc } from '../harness.mjs';

const css = readSrc('../ui/style.css');
const noComments = css.replace(/\/\*[\s\S]*?\*\//g, '');

/**
 * تنِ قاعده‌های یک انتخابگر — فقط میان `{` و نخستین `}` پس از آن.
 *
 * **همه** برمی‌گردند نه اولی. پوستهٔ شیشه‌ای عمداً لایه‌ای روی قاعده‌های
 * پایه است، پس `.card` دو بار تعریف شده و آنچه واقعاً رسم می‌شود آخری
 * است. نسخهٔ اول این تابع فقط اولی را می‌دید و ادعایش را روی قاعده‌ای
 * می‌سنجید که هیچ‌وقت غالب نمی‌شود — یعنی آزمونی که همیشه سبز می‌ماند.
 */
function ruleBodies(selector) {
  // مرزِ آغاز لازم است: جست‌وجوی سادهٔ رشته، `.pb-skin .card` را هم
  // «`.card`» می‌خواند و آخرین تعریفِ `.card` را همان می‌گیرد — قاعده‌ای
  // که به‌عمد پوستهٔ خودش را دارد و ربطی به این ادعا ندارد.
  const out = [];
  const pattern = new RegExp(`(^|[},])\\s*${selector.replace(/[.[\]()*+?^$|\\]/g, '\\$&')}\\s*\\{`, 'g');
  for (const match of noComments.matchAll(pattern)) {
    const open = noComments.indexOf('{', match.index);
    out.push(noComments.slice(open + 1, noComments.indexOf('}', open)));
  }
  return out;
}

/** آخرین تعریف — همان که در آبشار غالب می‌شود. */
const ruleBody = (selector) => ruleBodies(selector).pop() || null;


group('۲۱۹-الف. زمینه و پوسته از یک عنصر خوانده می‌شوند');
{
  // ریشهٔ اشکال ۱: هر توکنی که در `body[data-theme]` بازتعریف می‌شود، فقط
  // روی `body` و پایین‌ترش معنی دارد. مصرفش روی `html` یعنی پوستهٔ تیره
  // بی‌صدا نادیده گرفته می‌شود.
  const themed = ruleBody('body[data-theme="board"]') || '';
  const themedTokens = [...themed.matchAll(/(--[a-z0-9-]+):/g)].map((m) => m[1]);
  check('پوستهٔ تیره دست‌کم زمینه، سطح و خط را بازتعریف می‌کند',
    ['--ground', '--panel', '--line'].every((token) => themedTokens.includes(token)),
    themedTokens.length ? `${themedTokens.length} توکن` : 'بلوک پوسته پیدا نشد');

  const htmlRules = [...noComments.matchAll(/(^|\})\s*html\s*\{([^}]*)\}/g)].map((m) => m[2]);
  const themedOnHtml = htmlRules.filter((body) => themedTokens
    .some((token) => body.includes(`var(${token})`)));
  check('هیچ قاعدهٔ html توکنی را که فقط روی body تعریف شده مصرف نمی‌کند',
    themedOnHtml.length === 0,
    themedOnHtml.join(' | ').slice(0, 120));

  // لکه‌های نور رفتند (لایهٔ شیشه بازنشسته شد، دستهٔ ۲۷۱)، ولی خودِ
  // شرطِ اشکال ۱ سرِ جایش است: زمینه باید روی همان عنصری بنشیند که
  // توکنِ پوسته را می‌بیند، یعنی `body`.
  const groundRules = [...noComments.matchAll(/(^|\})\s*(html,\s*body|body)\s*\{([^}]*)\}/g)].map((m) => m[3]);
  check('زمینه روی body می‌نشیند، همان‌جا که توکنِ پوسته دیده می‌شود',
    groundRules.some((body) => /background(-color)?:\s*var\(--ground\)/.test(body)));
  check('لکه‌های نورِ خاموش دیگر روی body کشیده نمی‌شوند',
    !groundRules.some((body) => /var\(--ambient/.test(body)));

  // شبه‌عنصرِ منفی پشتِ زمینهٔ والدش می‌نشیند و همان، نسخهٔ اول را
  // نامرئی کرد. لایه‌بندی روی خودِ عنصر این دام را ندارد.
  check('نورِ محیط با شبه‌عنصرِ z-index منفی ساخته نمی‌شود',
    !/body::before/.test(noComments));
}


group('۲۱۹-ب. سطحِ کارت تخت است، و هیچ شیبی روی متنش نمی‌افتد');
{
  // ═══ چرا این ادعا وارونه شد (۱۴۰۵/۰۶/۲۸) ═══
  //
  // پیش از این، کارت یک نوارِ نورِ شیب‌دار داشت و ادعا این بود که آن نوار
  // «با واحد ثابت تمام شود تا به متن نرسد» — چون نسخهٔ درصدی‌اش در کارتِ
  // بلند روی برچسب‌ها می‌افتاد. حالا نوار اصلاً نیست: شیبش از
  // `--glass-sheen` می‌آمد که خنثی (`transparent`) شده بود، پس یک
  // `linear-gradient` نامرئی روی هر کارتِ برنامه کشیده می‌شد و فقط
  // هزینه داشت.
  //
  // ادعا حذف نشد، وارونه شد: تا وقتی سطحِ کارت تخت است، اشکال ۲ ممکن
  // نیست. اگر روزی کسی شیب را برگرداند، این ادعا قرمز می‌شود و همان‌جا
  // باید دوباره واحدِ ثابت را قفل کند.
  const card = ruleBody('.card') || '';
  check('کارت سطحِ یکدستِ توکن‌دار دارد، نه شیب',
    /background:\s*var\(--panel\)/.test(card) && !/linear-gradient/.test(card),
    card.trim().slice(0, 60));
}


group('۲۱۹-ج. `hidden` واقعاً مخفی می‌کند');
{
  // ریشهٔ اشکال ۳: هر جزئی که `display` می‌گذارد، `hidden` را می‌شکند.
  check('قاعدهٔ سراسری `hidden` هست و بر `display` اجزا غالب است',
    /\[hidden\]\s*\{\s*display:\s*none\s*!important/.test(noComments));
}


group('۲۱۹-د. شیشه‌ای نمانده که پشتیبان بخواهد');
{
  // ═══ چرا این گروه هم وارونه شد (۱۴۰۵/۰۶/۲۸) ═══
  //
  // سه پشتیبان داشتیم چون سطح‌ها نیمه‌شفاف بودند و `backdrop-filter`
  // داشتند: مرورگرِ بی‌پشتیبانی، «حرکت کمتر»، و چاپ. هر سه برای این بود
  // که متن روی متن نیفتد. حالا هیچ سطحی نه نیمه‌شفاف است نه تار، پس
  // خودِ شرط از بین رفته — و ادعا باید همان را قفل کند، نه پشتیبانی که
  // دیگر چیزی ندارد بپوشاند.
  check('هیچ `backdrop-filter` نمانده — تاری صفر، فقط هزینهٔ پردازش بود',
    !/backdrop-filter/.test(noComments));
  // سقف عمداً ۵۰٪ است: رنگِ **پوششیِ** کم‌رمق (مثل هایلایتِ هاورِ ماتریس)
  // هنوز مجاز است؛ آنچه ممنوع است سطحِ کارت‌نمایی است که خودش را سطح
  // جا می‌زند و زمینه از زیرش رد می‌شود.
  const sheer = [...noComments.matchAll(/background:\s*color-mix\(in srgb, var\(--panel\) (\d+)%, transparent\)/g)]
    .filter((m) => Number(m[1]) >= 50);
  check('هیچ سطحی نیمه‌شفاف نیست تا زمینه از زیرش رد شود',
    sheer.length === 0, sheer.map((m) => `${m[1]}%`).join('، '));
  check('چاپ همچنان سطحِ پر و بی‌سایه دارد',
    /@media print[\s\S]{0,400}box-shadow:\s*none/.test(noComments));

  // نگهبان ۱۱ فلشِ کشویی را می‌گیرد: میان‌بر `background` تصویرِ پس‌زمینه
  // را هم صفر می‌کند و فلش دقیقاً یک `background-image` است. بلوکی که
  // آن دام را ساخته بود رفته؛ ادعا می‌ماند تا با هر بلوکِ تازه‌ای هم
  // برقرار باشد.
  const inputRules = [...noComments.matchAll(/input\[type="date"\][^{]*\{([^}]*)\}/g)].map((m) => m[1]);
  const shorthand = inputRules.filter((body) => /(^|;)\s*background\s*:/.test(body));
  check('هیچ قاعدهٔ ورودی با میان‌بر `background` فلشِ کشویی را پاک نمی‌کند',
    shorthand.length === 0, shorthand.join(' | ').slice(0, 120));
}


group('۲۱۹-ه. زبانِ شکلی از توکن می‌آید');
{
  const root = ruleBody(':root') || '';
  // توکن‌های خنثای شیشه از هر دو پوسته برداشته شدند (دستهٔ ۲۷۱ کلاسِ
  // خطایش را قفل می‌کند). ادعا اینجا می‌ماند تا برنگردند: توکنی که
  // مقدارش `transparent` است، لبهٔ زیرش را بی‌صدا پاک می‌کند.
  for (const token of ['--glass', '--glass-2', '--glass-edge', '--glass-sheen',
    '--glass-blur', '--ambient-1', '--ambient-2', '--ambient-3', '--glow-accent']) {
    check(`توکن ${token} دیگر تعریف نمی‌شود`, !root.includes(`${token}:`));
  }
  // ── جغجغهٔ تازه: پوسته مات است، نه شیشه‌ای ─────────────────────────
  //
  // پیش از این جغجغه در جهتِ عکس بسته بود («گردی دست‌کم ۱۶ پیکسل»)، چون
  // شیشه بدون گردیِ کافی «شکسته» دیده می‌شود. حالا که سطح مات است، آن
  // قید معنایی ندارد و قیدِ درست وارونه‌اش است: گردی نباید دوباره بادکند
  // و تاری نباید برگردد. هر دو در توکن‌اند، پس هر دو یک‌جا سنجیده می‌شوند.
  const radius = Number(root.match(/--radius-lg:\s*([0-9.]+)px/)?.[1]);
  check('گردی کارت از ۱۴ پیکسل بیشتر نمی‌شود', radius > 0 && radius <= 14, `${radius}px`);
  check('تاری پس‌زمینه‌ای در کار نیست — سطح، کاغذ است نه شیشه',
    !/backdrop-filter/.test(noComments));
  // ── جغجغه وارونه شد، ۱۴۰۵/۰۶/۲۶ ──────────────────────────────────
  //
  // ادعای پیشین این بود که «--shadow-sm باید none باشد» — قفلِ تصمیمِ
  // پوستهٔ تختِ قبلی. صاحب پروژه آن تصمیم را صریح عوض کرد (زبانِ طراحی
  // Untitled UI). در آن زبان سایه تزئین نیست، نقش دارد: هر چیزی که خودش
  // یک *سطح* است پلهٔ xs را می‌گیرد و چیزی که شناور است پله‌های بلندتر.
  // پس ادعا حذف نشد، وارونه شد: مقیاس باید کامل باشد و پلهٔ نشسته باید
  // سایهٔ واقعی باشد، نه none. اگر کسی دوباره بی‌صدا صفحه را تخت کند،
  // همین‌جا قرمز می‌شود.
  const SHADOWS = ['--shadow-xs', '--shadow-sm', '--shadow-md', '--shadow-lg',
    '--shadow-xl', '--shadow-2xl', '--shadow-3xl'];
  for (const token of SHADOWS) {
    const value = root.match(new RegExp(token + ':\\s*([^;]+);'))?.[1]?.trim();
    check('پلهٔ ' + token + ' سایهٔ واقعی است، نه none',
      !!value && value !== 'none' && /rgba?\(/.test(value), value || 'تعریف نشده');
  }
  // لبهٔ داخلیِ دکمه — همان دو سایهٔ inset که دکمهٔ Untitled UI را از یک
  // مستطیلِ رنگی جدا می‌کند. در هر دو پوسته لازم است، چون روی زمینهٔ تیره
  // باید روشن باشد نه تیره، و یک تعریف برای هر دو کار نمی‌کند.
  for (const selector of [':root', 'body[data-theme="board"]']) {
    const block = ruleBody(selector) || '';
    check('لبهٔ داخلیِ دکمه در ' + selector + ' تعریف شده',
      /--shadow-skeuo:\s*[^;]*inset/.test(block));
  }
  // تاری در همهٔ نقطه‌ها از همین یک توکن می‌آید؛ عددِ سخت‌کدشده یعنی
  // خاموش‌کردنِ شیشه در یک جا اثر نمی‌کند و در جای دیگر می‌کند.
  // `blur(1px)` داخلِ شرطِ `@supports` تاریِ واقعی نیست — پرسشِ «مرورگر
  // این ویژگی را دارد؟» است و باید عددی ثابت بماند.
  const literalBlur = [...noComments.matchAll(/backdrop-filter:\s*blur\(([0-9.]+)px\)/g)]
    .filter((m) => m[1] !== '1');
  check('هیچ تاریِ سخت‌کدشده‌ای بیرون از توکن نمانده', literalBlur.length === 0,
    literalBlur.map((m) => m[1]).slice(0, 3).join('، '));
}

group('۲۱۹-و. متن فارسی روی فونتِ لاتینِ تک‌عرض نمی‌افتد');
{
  // ═══ ایرادی که این گروه جوابش است ═══
  //
  // «در قسمت‌هایی که نمودار به جدول اضافه کردی جدول قابل خوندن نیست و به
  // هم ریختگی ایجاد شده.» علتِ اصلی‌اش رنگ و چیدمان نبود، فونت بود:
  // `--mono` با «JetBrains Mono» شروع می‌شد و آن فونت حرف فارسی ندارد.
  // مرورگر برای هر حرفِ نداشته به فونت بعدی می‌افتد و پیوندِ خط فارسی
  // می‌شکند — «باقی‌مانده» روی صفحه «با قیما نده» دیده می‌شد.
  //
  // نگهبان ۵ سال‌ها پیش همین کلاس خطا را برای «ثانیه» ثبت کرده بود و
  // شرطش این بود که پشتهٔ تک‌عرض «پشتیبان فارسی داشته باشد». کافی نبود:
  // پشتیبان **آخرِ** صف بود و هیچ‌وقت به آن نمی‌رسید.
  const root = ruleBody(':root') || '';
  const mono = root.match(/--mono:\s*([^;]+);/)?.[1]?.trim() || '';
  check('نخستین فونتِ پشتهٔ عدد، فارسی‌دار است',
    /^Vazirmatn/.test(mono), mono.slice(0, 60));
  // هم‌عرضیِ رقم از `tabular-nums` می‌آید نه از فونت تک‌عرض.
  check('و هم‌عرضیِ رقم از tabular-nums می‌آید',
    /\.mono,\s*\.num\s*\{[^}]*tabular-nums/.test(noComments));
  // کدِ لاتین توکنِ خودش را دارد؛ آنجا متن فارسی نیست.
  check('کدِ لاتین پشتهٔ جداگانه دارد، تا تک‌عرضیِ واقعی از دست نرود',
    /--mono-code:/.test(root) && /code,\s*pre\s*\{[^}]*var\(--mono-code\)/.test(noComments));
}
