// سپردنِ فایل به مرورگر — یک راه، برای همهٔ خروجی‌ها.
//
// ═══ چرا این ماژول لازم شد ═══
//
// آزمونِ عملیِ ۱۴۰۵/۰۷/۰۲: در دو دورِ اولِ خروجیِ دیتا، تب نوشت «فایل با
// حجم ۵٬۸۸۲ کیلوبایت دانلود شد» و **هیچ فایلی روی دیسک نبود** — هم با
// ابزارِ خودکار و هم با کلیکِ دستیِ صاحب پروژه. از دورِ سوم به بعد همان
// دکمه کار کرد.
//
// هفت جای برنامه یک الگو داشتند:
//
//     link.click();
//     setTimeout(() => URL.revokeObjectURL(url), 0);
//
// یعنی نشانیِ فایل **صفر میلی‌ثانیه** بعد از کلیک باطل می‌شد، و پیوند هرگز
// به صفحه وصل نمی‌شد. مرورگر دانلود را ناهمگام شروع می‌کند؛ برای فایلِ
// چندمگابایتی ممکن است وقتی سراغِ نشانی برود که دیگر وجود ندارد — و
// بی‌صدا هیچ کاری نکند. خطای گاه‌به‌گاه، دقیقاً همان چیزی که دیده شد.
//
// ═══ دو قاعده ═══
//
// ۱. نشانی تا خروجیِ **بعدی** زنده می‌ماند، نه صفر میلی‌ثانیه. حافظه‌اش
//    یک فایل است، نه انباشته.
// ۲. هیچ‌کس نمی‌تواند بداند مرورگر واقعاً ذخیره کرد یا نه. پس رابط باید
//    «به مرورگر سپرده شد» بگوید، نه «دانلود شد» — و پیوندِ دستی بدهد؛
//    کلیکِ خودِ کاربر روی پیوند، مطمئن‌ترین راهِ دانلود است.

let last = null;

/** آخرین فایلِ سپرده‌شده — برای پیوندِ دستیِ «اگر دانلود شروع نشد». */
export function lastSaved() {
  return last;
}

/** فایل را به مرورگر می‌سپارد و نشانی‌اش را تا خروجیِ بعدی نگه می‌دارد. */
export function saveBlob(blob, filename) {
  if (last?.url) URL.revokeObjectURL(last.url);
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.style.display = 'none';
  // بعضی مرورگرها کلیک روی پیوندِ جدا از صفحه را نادیده می‌گیرند.
  document.body.appendChild(link);
  link.click();
  link.remove();
  last = { url, filename, bytes: blob.size };
  return last;
}
