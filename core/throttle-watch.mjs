// تشخیصِ سهمیهٔ بالادست — وقتی «نیامد» یعنی «نگذاشتند بیاید».
//
// ═══ چرا این لازم شد ═══
//
// آزمونِ واقعیِ صاحب پروژه، سه اجرای پشت سر هم روی همان ۳۰۰ ابزار/روز با
// هدرهای کامل:
//
//     اجرا    داده آمد   خالی   میانگینِ پاسخ
//     اول        ۲۹۴       ۰      ۷۰۱ms
//     دوم        ۱۷۸     ۱۱۰    ۱٬۳۰۵ms
//     سوم          ۰     ۳۰۰       ۶۵ms
//
// اجرای سوم سیصد درخواست را در **پنج ثانیه** تمام کرد. این پاسخِ بورس
// نیست؛ یک «نه»ی آماده است که لبه فوری پس می‌دهد. و شکلش این است:
//
//     HTTP 200   {"tradeHistory":[]}
//
// نه ۴۲۹، نه ۴۰۳، نه خطا. **دقیقاً همان چیزی که یک روزِ بی‌معامله
// برمی‌گرداند.** برای همین خروجیِ هفتگیِ گزارش‌شده ۳۵۹ ابزار/روز را
// «ریزمعامله نیامد» نوشت، در حالی که داده روی بورس بود و چند دقیقه بعد
// با درخواستِ تکی کامل آمد.
//
// ═══ معیارِ تشخیص، و چرا این یکی ═══
//
// «پاسخِ خالی» به‌تنهایی معیار نیست — روزِ واقعاً بی‌معامله هم همان است.
// معیار این است: **تابلوی روزانه می‌گوید آن روز معامله شده، و هر دو پرچم
// خالی برگشتند** — و این چند بار **پشت سر هم** تکرار شود.
//
// یکی‌اش عادی است (بالادست گاهی یک روز را نمی‌دهد). ده‌تای پیاپی نه:
// احتمالِ اینکه ده ابزار/روزِ متوالی هرکدام تابلوی پرمعامله داشته باشند و
// هر بیست درخواست خالی برگردد، در برابر «سهمیه بسته شد» ناچیز است.
//
// مرجعِ نامعلوم و صفرِ تأییدشده هیچ رأیی ندارند: اولی چیزی نمی‌داند و
// دومی می‌گوید خالی **درست** است. فقط موردی شمرده می‌شود که تابلو خودش
// تکذیبش کند.

/** چند ابزار/روزِ پیاپیِ **تکذیب‌شده با تابلو** تا حکمِ «سهمیه». */
export const THROTTLE_STREAK = 10;

/**
 * همان، وقتی تابلویی در کار نیست.
 *
 * ═══ R5-09: چرا این دومی لازم شد ═══
 *
 * معیارِ اول به تابلوی روزانه تکیه دارد — ولی سهمیه **تابلو را هم**
 * می‌بندد. در فایلِ واقعیِ ۲۰۲۶۰۷۱۴ تا ۲۰۲۶۰۹۲۱، از ۱۵۹ ابزار فقط ۱۰ تا
 * تابلو داشتند؛ یعنی ناظر دقیقاً ۱۰ رأی در دست داشت و با همان ۱۰ تا حکم
 * داد. یکی کمتر، و هیچ حکمی صادر نمی‌شد و هر ۳٬۶۸۵ درخواست می‌رفت.
 *
 * تکیه بر شانس، تشخیص نیست. پس معیارِ دومی هست که به تابلو نیاز ندارد:
 * رشتهٔ بلندی از پاسخِ خالی که **هیچ راهی برای سنجشش نداریم**. سقفش
 * بالاتر است چون شاهدش ضعیف‌تر است — ولی چهل ابزار/روزِ پیاپیِ خالیِ
 * سنجش‌ناپذیر هم دیگر «بازارِ ساکت» نیست، و خرج‌کردنِ سهمیه رویش
 * قابل‌دفاع نیست.
 */
export const BLIND_STREAK = 40;

/**
 * پنجرهٔ کشویی، برای فازِ **تدریجیِ** بستن.
 *
 * ═══ R5-10: چرا رشتهٔ پیاپی کافی نبود ═══
 *
 * دو معیارِ بالا رشتهٔ **پیاپی** می‌شمارند، و آن فقط فازِ کاملاً بستهٔ
 * سهمیه را می‌گیرد. ولی اندازه‌گیری نشان داد بستن تدریجی است — اجرای
 * دومِ آزمونِ بار، ۱۷۸ موفق و ۱۱۰ خالیِ درهم:
 *
 *     xx........x.......xx.....
 *     .........xx0x0000000000x0
 *
 * در این فاز هر پاسخِ موفق رشته را صفر می‌کند، پس ناظر تا فازِ کامل صبر
 * می‌کند و در این فاصله ده‌ها ابزار/روز «نیامد» برچسب می‌خورند — علتِ
 * غلط، چون آن‌ها هم قربانیِ سهمیه‌اند. در خروجیِ واقعیِ ۲۰۲۶۰۹۱۴ تا
 * ۲۰۲۶۰۹۲۱ دقیقاً ۵۷ ردیف چنین شدند، ۵۰تایش در همان روزِ اول.
 *
 * پس معیارِ سوم نسبت را در پنجره‌ای کشویی می‌سنجد: اگر بیشترِ آخرین
 * `WINDOW` ابزار/روزِ **مرجع‌دار** تکذیب شده باشند، فاز شروع شده.
 * پنجره عمداً کوچک نیست تا یک بدشانسیِ محلی حکم ندهد.
 */
export const WINDOW = 25;
export const WINDOW_DENIED = 15;

/**
 * ناظرِ سهمیه برای یک اجرا.
 *
 * حالت روی همین شیء می‌ماند، نه در ماژول: دو اجرای هم‌زمان نباید رأیِ
 * هم را خراب کنند، و آزمون باید بتواند نمونهٔ تمیز بسازد.
 */
export function makeThrottleWatch({
  streak = THROTTLE_STREAK, blindStreak = BLIND_STREAK,
  window = WINDOW, windowDenied = WINDOW_DENIED,
} = {}) {
  let run = 0, blind = 0, worst = 0, since = 0, denied = 0;
  // پنجرهٔ کشویی فقط ابزار/روزِ **مرجع‌دار** را می‌گیرد، چون تنها آن
  // تکذیب‌پذیر است. بی مرجع، معیارِ `blind` کارِ خودش را می‌کند.
  const recent = [];
  // کلیدِ ابزار/روزهایی که در پنجره **تکذیب** شده‌اند. وقتی حکم صادر
  // می‌شود، همین‌ها مدرکش بوده‌اند — پس همین‌ها هم قربانیِ سهمیه‌اند و
  // نباید «نیامد» برچسب بخورند. (R5-10)
  const suspects = [];
  let recentDenied = 0;
  const ratioHit = () => recent.length >= window && recentDenied >= windowDenied;
  const hit = () => run >= streak || blind >= blindStreak || ratioHit();

  return {
    /**
     * یک پاسخ را ثبت می‌کند و می‌گوید آیا از این لحظه «سهمیه» است.
     *
     * `tape` همان چیزی است که `chooseTape` برگردانده: `emptyBoth` و
     * `reference` را از آن می‌خوانیم.
     */
    saw(tape, key = '') {
      const ref = tape?.reference;
      const known = Boolean(ref) && (Number(ref.trades) > 0 || Number(ref.volume) > 0);
      // ═══ R5-17: دو جور تکذیب ═══
      //
      // `emptyBoth`: هیچ پرچمی چیزی نداد. `falseEmpty`: پرچمِ اصلی خالی
      // آمد و نوار از `true`ِ همیشه‌بریده پر شد. دومی تا امروز «داده آمد»
      // خوانده می‌شد و رشته را صفر می‌کرد — در آزمونِ عملی ۱۳ ردیف همین
      // شکل را داشتند، درهم با ردیف‌های سهمیه.
      //
      // ولی فقط اولی **مظنون** می‌شود: ردیفِ `falseEmpty` دادهٔ واقعی
      // دارد و برچسبِ «سهمیه» آن را پنهان می‌کرد.
      const empty = tape?.emptyBoth === true;
      const refused = empty || (tape?.falseEmpty === true && known);

      // ═══ پنجرهٔ کشویی، پیش از هر صفرکردنی ═══
      //
      // برخلاف رشته، پنجره با یک پاسخِ موفق پاک نمی‌شود — و نکتهٔ فازِ
      // تدریجی دقیقاً همین است.
      if (known) {
        recent.push(refused ? 1 : 0);
        suspects.push(empty ? String(key || '') : '');
        if (refused) recentDenied += 1;
        if (recent.length > window) { recentDenied -= recent.shift(); suspects.shift(); }
      }

      // ردیفی که داده آورد هر دو رشته را صفر می‌کند: لوله باز است —
      // مگر داده فقط از پرچمِ بریده آمده باشد.
      if (!refused) { run = 0; blind = 0; return hit(); }
      // صفرِ تأییدشده هم همین‌طور — تابلو جواب داده و جوابش با نوار
      // می‌خواند؛ سالم‌ترین حالتِ ممکن است، نه نشانهٔ خرابی.
      if (ref && ref.quiet === true) { run = 0; blind = 0; return hit(); }

      denied += 1;
      if (known) run += 1; else blind += 1;
      const streakNow = known ? run : blind;
      if (streakNow > worst) worst = streakNow;
      if (hit() && !since) since = Date.now();
      return hit();
    },
    /** آیا همین حالا حکمِ سهمیه برقرار است. */
    throttled() { return hit(); },
    /** شرحِ وضعیت، برای پیام رابط و برگ راهنما. */
    state() {
      return {
        run, blind, worst, streak, blindStreak, since, denied,
        windowSize: recent.length, windowDenied: recentDenied,
        // فقط وقتی معنا دارد که حکم صادر شده باشد؛ وگرنه فهرستی از
        // خالی‌های عادی است و برچسب‌زدنشان ادعای بی‌پشتوانه می‌شود.
        suspects: hit() ? suspects.filter(Boolean) : [],
        throttled: hit(),
        // کدام معیار حکم داد — جمله‌اش فرق می‌کند و کاربر باید بداند.
        by: run >= streak ? 'board' : (blind >= blindStreak ? 'blind' : (ratioHit() ? 'ratio' : '')),
      };
    },
    reset() { run = 0; blind = 0; since = 0; recent.length = 0; suspects.length = 0; recentDenied = 0; },
  };
}

/** جملهٔ فارسیِ حکم — یک جا نوشته می‌شود تا رابط و فایل یکی بگویند. */
export function throttleNote(state) {
  if (!state?.throttled) return '';
  const tail = ' دریافت همین‌جا متوقف شد تا سهمیه بیشتر مصرف نشود.'
    // R5-17: «چند ساعت بعد دوباره امتحان کنید» نمی‌گفت **چطور**، و راهِ
    // بدیهی — ساختنِ خروجیِ تازه — دقیقاً همان است که داده را دور می‌ریزد.
    + ' دست‌کم نیم ساعت بعد «تلاش تکمیلی» را در همین صفحه بزنید؛ آنچه تا اینجا آمده سرِ جایش می‌ماند.'
    + ' ساختنِ خروجیِ تازه همه را از صفر می‌گیرد.';
  if (state.by === 'ratio') {
    return `از ${state.windowSize} ابزار/روزِ اخیر، ${state.windowDenied} تا خالی برگشتند`
      + ' در حالی که تابلوی روزانه‌شان معامله ثبت کرده. بستنِ سهمیه تدریجی است و این آغازش است —'
      + ' ادامه‌دادن هم داده نمی‌آورد و هم پنجره را تمدید می‌کند.' + tail;
  }
  if (state.by === 'blind') {
    return `بالادست ${state.blind} ابزار/روزِ پیاپی را خالی برگرداند و تابلوی روزانهٔ هیچ‌کدام هم نیامد،`
      + ' پس حتی نمی‌شود سنجید که واقعاً بی‌معامله بوده‌اند یا نه.'
      + ' وقتی تابلو هم خالی برمی‌گردد، خودِ آن نشانهٔ سهمیه است.' + tail;
  }
  return `بالادست ${state.run} ابزار/روزِ پیاپی را خالی برگرداند در حالی که تابلوی روزانه‌شان معامله ثبت کرده —`
    + ' این الگوی سهمیه است، نه بازارِ بی‌معامله.' + tail;
}
