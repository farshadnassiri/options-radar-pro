// سلامتِ عکسِ زندهٔ دیده‌بان — «این عدد چند لحظه پیش است؟»
//
// ═══ ایرادی که این ماژول برای آن ساخته شد ═══
//
// گزارش بازآزماییِ ۱۴۰۵/۰۶/۱۶:
//
//   «`watchTicks` روی ۹۰ ثابت ماند. `watchAgeSec` از ۱۶۳ به ۲۹۰ ثانیه رسید.
//    در همان زمان بازار باز، `paused=false`، `watchConsecutiveFails=0`،
//    `queueDepth=0` و `inflight=2` بود. یعنی برنامه توقف را اعلام نکرده،
//    اما عکس زنده بیش از ۴ دقیقه تازه نشده است. برای یک ابزار معاملاتی این
//    وضعیت باید خطای صریح یا توقف کنترل‌شده بدهد.»
//
// نکتهٔ دقیقِ گزارش این است: **هیچ شمارنده‌ای دروغ نمی‌گفت.** خطا صفر بود،
// چون خطایی رخ نداده بود؛ توقف اعلام نشده بود، چون توقفی اعلام نشده بود.
// آنچه نبود، خودِ سؤال بود: «عکس چقدر کهنه است، و این مقدار پذیرفتنی است؟»
//
// دو حالتِ کاملاً متفاوت تا امروز یک ظاهر داشتند: «بازار بسته است، پس عکس
// کهنه طبیعی است» و «بازار باز است و ما جا مانده‌ایم». تفاوتشان برای کسی که
// می‌خواهد سفارش بگذارد، همه‌چیز است.

import { num } from './num.mjs';

// جملهٔ نمایشی است، پس رقمش فارسی نوشته می‌شود — همان قاعده‌ای که
// `manualNote` در `core/manual-price.mjs` هم رعایتش می‌کند. عددهای ساختاری
// (`ageSec`، `limitSec`) خام می‌مانند تا مصرف‌کننده بتواند رویشان بسنجد.
const fa = (value) => String(value).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[+d]);

/**
 * سقفِ کهنگیِ قابل قبول، بر حسب ثانیه.
 *
 * ضریبِ چهار عمدی است: یک دورِ ازدست‌رفته اتفاق است، دو دور بی‌شانسی، ولی
 * چهار دور یعنی چیزی درست کار نمی‌کند. کفِ ۳۰ ثانیه جلوی هشدارِ کاذب را روی
 * فاصله‌های خیلی کوتاه می‌گیرد.
 */
export const watchStaleLimitSec = (intervalSec) => Math.max(30, num(intervalSec, 5) * 4);

/**
 * حکمِ تازگی.
 *
 * `at` لحظهٔ آخرین عکسِ موفق است (میلی‌ثانیه)، یا `null`/صفر وقتی هیچ عکسی
 * ثبت نشده. بازارِ بسته هرگز کهنه شمرده نمی‌شود: آنجا کهنگی خبر نیست.
 *
 * `ageSec` وقتی هیچ عکسی نبوده `null` است نه صفر — «نمی‌دانم» با «همین حالا»
 * یکی نیست، و همان اشتباهی است که دور پیش روی «سنِ مظنه» گرفته شد.
 */
export function watchHealth({ open = false, at = 0, now = Date.now(), intervalSec = 5 } = {}) {
  const limitSec = watchStaleLimitSec(intervalSec);
  const stamp = num(at, 0);
  const ageSec = stamp > 0 ? Math.max(0, Math.round((num(now, Date.now()) - stamp) / 1000)) : null;
  if (!open) return { stale: false, ageSec, limitSec, why: '' };
  if (ageSec === null) {
    return {
      stale: true, ageSec, limitSec,
      why: 'بازار باز است ولی هنوز هیچ عکسی از تابلو گرفته نشده.',
    };
  }
  if (ageSec <= limitSec) return { stale: false, ageSec, limitSec, why: '' };
  return {
    stale: true, ageSec, limitSec,
    why: `عکس تابلو ${fa(ageSec)} ثانیه است که تازه نشده، در حالی که بازار باز است`
      + ` و سقف قابل قبول ${fa(limitSec)} ثانیه است. عددهای روی صفحه به همان اندازه کهنه‌اند.`,
  };
}
