// کف و سقفِ **امروز** — آنچه واقعاً امروز دیده شده، نه کف و سقفِ تاریخ.
//
// ═══ ایرادی که این فایل جوابش است ═══
//
// «کف امروز» و «سقف امروز» در واقع کف و سقف کل بازهٔ تاریخی‌اند.
// ریزمعامله‌های امروز وارد محاسبهٔ این دو مرجع نمی‌شوند. نام شرط با
// داده‌ای که سنجیده می‌شود تطابق ندارد.
//
// درست بود. هر دو تب `min`/`max` سریِ **روزانهٔ بازه** را به‌عنوان «کف و
// سقف امروز» به موتور شرط می‌دادند. یعنی شرطِ «۵٪ بالاتر از کف امروز» در
// عمل «۵٪ بالاتر از کفِ سه‌ماههٔ گذشته» بود — عددی که کاربر نخواسته و
// نمی‌داند دارد رویش شرط می‌گذارد.
//
// ═══ چرا «مشاهده‌شده» و نه «واقعی» ═══
//
// کف و سقفِ واقعیِ امروزِ یک **ترکیب**، از تابلو نمی‌آید: تابلو کف و سقفِ
// هر ابزار را جدا می‌دهد و کمینهٔ تفاضلِ دو پا، تفاضلِ کمینه‌ها نیست.
// ساختنش ریزمعاملهٔ همهٔ پاهاست — همان چیزی که برای یک ترکیب گرفته می‌شود
// و برای صد ترکیب در هر تیک، صد‌ها درخواست است.
//
// پس آنچه صادقانه در دسترس است همین است: **کف و سقفِ آنچه از آغاز رصد
// دیده‌ایم.** و دقیقاً با همین نام گفته می‌شود، نه با نامِ «کف امروز» که
// ادعای بیشتری دارد. پیش از نخستین تیک، عدد ندارد و `NaN` می‌ماند — که
// یعنی شرط برقرار نمی‌شود، نه اینکه با صفر برقرار شود.
//
// ═══ روز عوض شود، همه‌چیز پاک می‌شود ═══
//
// تبی که شب باز مانده و صبح تیک می‌زند، نباید کفِ دیروز را «کف امروز»
// بخواند. `observe` تاریخ می‌گیرد و تاریخِ تازه دفتر را از نو می‌سازد.

import { num } from './num.mjs';

const finite = (value) => Number.isFinite(value);

/**
 * دفترِ کف و سقفِ مشاهده‌شدهٔ امروز، به تفکیکِ ترکیب.
 *
 * حالت‌دار است و عمداً بیرون از موتورِ شرط: موتور بی‌حالت می‌ماند و این
 * یکی تنها چیزی است که بین دو تیک زنده می‌ماند.
 */
export function makeDayRange() {
  let date = 0;
  const rows = new Map();

  const reset = (nextDate = 0) => {
    date = Math.trunc(num(nextDate, 0)) || 0;
    rows.clear();
  };

  return {
    get date() { return date; },
    get size() { return rows.size; },
    reset,

    /**
     * یک مشاهدهٔ تازه. عددِ نداشته وارد نمی‌شود — `NaN` کف را صفر نمی‌کند.
     *
     * @returns ردیفِ به‌روزشده، یا `null` اگر مشاهده وارد نشد.
     */
    observe(key, value, { date: on = 0 } = {}) {
      const id = String(key ?? '');
      const seen = num(value, NaN);
      if (!id || !finite(seen)) return null;
      const day = Math.trunc(num(on, 0)) || 0;
      if (day && day !== date) reset(day);
      const row = rows.get(id);
      if (!row) {
        const fresh = { low: seen, high: seen, first: seen, last: seen, count: 1 };
        rows.set(id, fresh);
        return { ...fresh };
      }
      row.low = Math.min(row.low, seen);
      row.high = Math.max(row.high, seen);
      row.last = seen;
      row.count += 1;
      return { ...row };
    },

    /** کف و سقفِ یک ترکیب. نبودش `NaN` است، نه صفر. */
    get(key) {
      const row = rows.get(String(key ?? ''));
      if (!row) return { low: NaN, high: NaN, first: NaN, last: NaN, count: 0 };
      return { ...row };
    },
  };
}
