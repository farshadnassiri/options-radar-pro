// «امروز» یعنی چه — یک تعریف، برای کل برنامه.
//
// ═══ چرا ماژول جدا، برای یک تابع ═══
//
// ممیزی (۱۴۰۵/۰۶/۲۴): «تعریف امروز یکدست نیست. مسیر زنده تاریخ تهران را
// درست استفاده می‌کند، اما انتخابگر بازهٔ مشترک از UTC استفاده می‌کند.
// بین نیمه‌شب تهران و نیمه‌شب UTC امکان یک روز اختلاف وجود دارد.»
//
// درست بود، و اختلاف کوچک نیست: تهران ‎+۳:۳۰‎ است، پس از ۲۰:۳۰ به بعدِ هر
// شب، UTC هنوز روز قبل است. یعنی دقیقاً در ساعت‌هایی که کاربر بعد از
// بستن بازار می‌نشیند و کار می‌کند، «امروز»ِ تقویم با «امروز»ِ عکس تابلو
// یکی نبود.
//
// این تابع پیش از این داخل `core/live-day.mjs` بود. اگر همان‌جا می‌ماند،
// `core/history-range.mjs` — که هیچ ربطی به عکس تابلو ندارد — برای یک
// تاریخ باید کل مسیر روز جاری را وارد می‌کرد. یک فایل شش‌خطی ارزانتر از
// یک وابستگی بی‌ربط است، و مهم‌تر: جایی که همه از آن بخوانند، هیچ‌کس
// نسخهٔ خودش را نمی‌نویسد.

/**
 * روز تهران به شکل YYYYMMDD میلادی. صفر یعنی ساعتِ ورودی خوانده نشد.
 *
 * صفر برمی‌گرداند و پرتاب نمی‌کند: فراخوان‌ها همه در مسیرِ نمایش‌اند و
 * «نمی‌دانم کدام روز» را باید بتوانند به کاربر بگویند، نه اینکه صفحه را
 * قرمز کنند.
 */
export function tehranDateNumber(at = Date.now()) {
  const time = Number(at);
  if (!Number.isFinite(time)) return 0;
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Tehran', year: 'numeric', month: '2-digit', day: '2-digit',
  }).formatToParts(new Date(time)).filter((part) => part.type !== 'literal')
    .map((part) => [part.type, part.value]));
  return Number(`${parts.year || ''}${parts.month || ''}${parts.day || ''}`) || 0;
}
