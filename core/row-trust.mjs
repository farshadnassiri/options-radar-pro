// اعتبارِ ردیف — «این عدد را می‌شود مبنای سفارش کرد؟»
//
// ═══ ایرادی که این ماژول برای آن ساخته شد ═══
//
// گزارش عملیاتیِ ۱۴۰۵/۰۶/۱۶: یک Long Put دو روزه با بهای اجرای ۱٬۰۰۱ ریال
// «بازده دوره ۱۳۵٬۰۹۳٪ و بازده ماهانه ۲٬۰۲۶٬۳۹۶٪» را در **رتبهٔ اول** نشان
// داد. همان ردیف هم‌زمان دو هشدار داشت — «آفست ناممکن» و «بازده نامتعارف» —
// ولی هشدار فقط یک برچسب کنار ردیف بود:
//
//   «هشدار وجود دارد، اما ردیف نامتعارف همچنان رتبه را می‌رباید و برای یک
//    تریدر نتیجهٔ عملی جدول را مخدوش می‌کند.»
//
// ═══ چرا حذف نمی‌شود ═══
//
// حذف کردنِ ردیف، دادهٔ واقعی را پنهان می‌کند و همان قاعدهٔ صداقتِ عددی را از
// سمت دیگر می‌شکند: گاهی همان ردیف واقعاً یک آربیتراژ است و باید دیده شود.
// پس ردیف می‌ماند، هشدارش می‌ماند، ولی **صدر را نمی‌گیرد**: در هر مرتب‌سازی
// بعد از همهٔ ردیف‌های قابل اتکا می‌نشیند، و شاخصِ «بهترین» او را نمی‌خواند.
//
// جداییِ «هشدار» از «مشکوک» عمدی است. هشدارها زیادند و بیشترشان توصیفی‌اند
// («سررسید نزدیک»، «چند سررسید — بازده تقریبی»). فقط دو تا **خودِ عدد را**
// بی‌اعتبار می‌کنند، و فهرست کوتاه می‌ماند تا معنی‌اش رقیق نشود: اگر نیمی از
// جدول «مشکوک» شود، مشکوک بودن دیگر خبر نیست.

/**
 * هشدارهایی که ردیف را از رتبه‌بندی پایین می‌آورند، و دلیلشان.
 *
 * · «بازده نامتعارف» — عدد از مظنه‌ای آمده که بازار به آن قیمت نمی‌دهد.
 *   بهای اجرای ۱٬۰۰۱ ریالی مخرجِ کسر است؛ کسرِ درست، ولی مخرجی که در بازار
 *   واقعی پر نمی‌شود.
 * · «آفست ناممکن» — سمت خروجِ دست‌کم یک پا خالی است. بازدهی که نمی‌شود از آن
 *   بیرون آمد، بازده نیست.
 */
export const DEMOTING_FLAGS = new Map([
  ['بازده نامتعارف', 'عدد از مظنه‌ای آمده که بازار به آن قیمت نمی‌دهد'],
  ['آفست ناممکن', 'سمت خروجِ دست‌کم یک پا خالی است — ورود ممکن، خروج نه'],
]);

/**
 * از فهرست هشدارهای یک ردیف، حکمِ اعتبار.
 *
 * `reasons` ترتیبِ `DEMOTING_FLAGS` را نگه می‌دارد نه ترتیبِ ورودی را، تا دو
 * ردیف با یک مشکل، یک جملهٔ یکسان بگیرند.
 */
export function rowTrust(warn = []) {
  const has = new Set(Array.isArray(warn) ? warn : []);
  const reasons = [];
  for (const [flag, why] of DEMOTING_FLAGS) if (has.has(flag)) reasons.push({ flag, why });
  return { suspect: reasons.length > 0, reasons };
}

/** آیا این ردیف مشکوک است. برای جاهایی که فقط پرچم لازم دارند. */
export const isSuspect = (row) => row?.suspect === true;

/** جملهٔ کوتاهِ کنارِ ردیف یا کارت، وقتی مشکوک است. */
export function suspectNote(row) {
  const reasons = row?.suspectWhy || [];
  if (!reasons.length) return '';
  return `این ردیف رتبه نمی‌گیرد: ${reasons.map((x) => x.why).join('؛ ')}.`;
}

/**
 * مقایسه‌گرِ «مشکوک آخر».
 *
 * روی هر مرتب‌سازی سوار می‌شود: اول اعتبار، بعد کلیدِ انتخابیِ کاربر. جهتِ
 * مرتب‌سازی روی این لایه اثر ندارد — مشکوک در صعودی هم آخر است، چون بحث
 * ترتیبِ عدد نیست، بحث این است که عددش خوانده نشود.
 */
export const trustFirst = (a, b) => (isSuspect(a) ? 1 : 0) - (isSuspect(b) ? 1 : 0);

/**
 * بهترین ردیف بر اساس یک کلید، با نادیده‌گرفتنِ ردیف‌های مشکوک.
 *
 * اگر **همه** مشکوک باشند، `null` برمی‌گردد نه بهترینِ مشکوک‌ها: کارتِ
 * «بهترین بازده ماهانه» که عددِ بی‌اعتبار نشان بدهد، از کارتِ خالی بدتر است.
 */
export function bestTrusted(rows = [], key = 'retMonthPct') {
  let best = null;
  for (const row of rows) {
    if (isSuspect(row)) continue;
    const v = Number(row?.[key]);
    if (!Number.isFinite(v)) continue;
    if (best === null || v > Number(best[key])) best = row;
  }
  return best;
}
